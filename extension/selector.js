// Demo Director — selector generation for the element picker.
// Prefers stable hooks (data-testid, data-ui, sane ids) over generated class
// names, which React/styled-components rewrite between builds.
//
// similar(el)  → every element like this one, e.g. every row's text spans.
// position(el) → the same spot in each repeated group, e.g. the date subtitle
//                (2nd span) on every row of a list. Default for veils.
// unique(el)   → only this element.

(function (root) {
  const TEST_ATTRS = ['data-testid', 'data-test-id', 'data-test', 'data-qa', 'data-cy', 'data-ui'];
  const MAX_TAG_PATH = 6;
  const MAX_SCOPE_ANCESTORS = 2;

  const quote = (v) => `"${String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  const cssEscape = (v) => (root.CSS && root.CSS.escape ? root.CSS.escape(v) : String(v).replace(/[^\w-]/g, (c) => `\\${c}`));

  // Ids generated by React (":r1:"), UI kits ("radix-…") or hashes are unstable.
  function stableId(id) {
    return !!id && !/[:]|^\d|\d{3,}|^(radix|headlessui|mui|react|ember)-/i.test(id) && id.length <= 40;
  }

  // "pane-item-42", "row_7f3a9c" → a prefix match, so the selector generalises
  // across rows instead of pinning one document's id.
  const ID_SUFFIX = /^(.*?[-_:.])([A-Za-z0-9]*\d[A-Za-z0-9-]*)$/;

  function stableToken(el, exact = false) {
    for (const attr of TEST_ATTRS) {
      const v = el.getAttribute(attr);
      if (!v) continue;
      const m = !exact && attr !== 'data-ui' && ID_SUFFIX.exec(v);
      return m && m[1].length >= 3 ? `[${attr}^=${quote(m[1])}]` : `[${attr}=${quote(v)}]`;
    }
    if (stableId(el.id)) return `#${cssEscape(el.id)}`;
    return null;
  }

  // Strongest identity: test ids / ids beat data-ui, which Sanity UI puts on
  // every primitive ("Box", "Text") and is only useful in combination.
  function strongToken(el, exact = false) {
    const t = stableToken(el, exact);
    return t && !t.startsWith('[data-ui=') ? t : null;
  }

  function tagToken(el) {
    const ui = el.getAttribute('data-ui');
    const role = el.getAttribute('role');
    let t = el.localName;
    if (ui) t += `[data-ui=${quote(ui)}]`;
    else if (role) t += `[role=${quote(role)}]`;
    return t;
  }

  function count(sel, doc) {
    try {
      return doc.querySelectorAll(sel).length;
    } catch {
      return -1;
    }
  }

  function nthOfType(el) {
    const sibs = el.parentElement ? [...el.parentElement.children].filter((c) => c.localName === el.localName) : [];
    return sibs.length > 1 ? `:nth-of-type(${sibs.indexOf(el) + 1})` : '';
  }

  function similar(el, { position = false } = {}) {
    const doc = el.ownerDocument;
    const htmlEl = doc.documentElement;

    // 1. Own token, or a child-combinator path of tags up to the nearest strong ancestor.
    let core;
    const own = strongToken(el);
    let p;
    if (own) {
      core = own;
      p = el.parentElement;
    } else {
      // With `position`, pin the position at the lowest level that actually has
      // same-type siblings (e.g. the 2nd Box in each row, when each Box holds
      // one span), so title and subtitle stop matching each other.
      const els = [el];
      p = el.parentElement;
      while (p && p !== htmlEl && p !== doc.body && els.length < MAX_TAG_PATH) {
        if (strongToken(p)) break;
        els.unshift(p);
        p = p.parentElement;
      }
      let pin = -1;
      if (position) for (let k = els.length - 1; k >= 0 && pin < 0; k--) if (nthOfType(els[k])) pin = k;
      const path = els.map((e, k) => tagToken(e) + (k === pin ? nthOfType(e) : ''));
      const anchor = p && p !== htmlEl && p !== doc.body ? strongToken(p) : null;
      core = (anchor ? `${anchor} > ` : '') + path.join(' > ');
      if (anchor) p = p.parentElement;
    }

    // 2. Scope with a couple of strong ancestors (descendant combinator)…
    const scope = [];
    while (p && p !== htmlEl && scope.length < MAX_SCOPE_ANCESTORS) {
      const strong = strongToken(p);
      if (strong) scope.unshift(strong);
      p = p.parentElement;
    }

    // 3. …then drop any scope that doesn't narrow the match.
    let parts = [...scope, core];
    const target = count(parts.join(' '), doc);
    for (let i = 0; i < parts.length - 1; ) {
      const trial = parts.filter((_, k) => k !== i);
      if (count(trial.join(' '), doc) === target) parts = trial;
      else i++;
    }
    return parts.join(' ');
  }

  function unique(el) {
    const doc = el.ownerDocument;
    const steps = [];
    let cur = el;
    while (cur && cur !== doc.documentElement) {
      const strong = strongToken(cur, true);
      if (strong) {
        steps.unshift(strong);
        if (count(steps.join(' > '), doc) === 1) return steps.join(' > ');
        steps.shift();
      }
      steps.unshift(cur.localName + nthOfType(cur));
      if (count(steps.join(' > '), doc) === 1) return steps.join(' > ');
      cur = cur.parentElement;
    }
    return ['html', ...steps].join(' > ');
  }

  const position = (el) => similar(el, { position: true });
  const api = { similar, position, unique, count, stableToken };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.DDSelector = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
